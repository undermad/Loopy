export type GameIconName = keyof typeof ICONS;

export const GAME_ICON_NAMES = Object.keys(ICONS) as GameIconName[];

function isGameIcon(name: string): name is GameIconName {
  return name in ICONS;
}

export interface GameIconProps {
  name: string;
  className?: string | undefined;
  size?: number | string;
  color?: string | undefined;
}

export function GameIcon({ name, className, size, color }: GameIconProps) {
  const icon = isGameIcon(name) ? ICONS[name] : Puzzle;
  return createElement(icon, {
    'aria-hidden': true,
    className,
    ...(size === undefined ? {} : { size }),
    ...(color === undefined ? {} : { color }),
  });
}
